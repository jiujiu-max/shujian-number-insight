export function fillPersonalExample(text:string,age:number) {
 const i=age<=24?0:age<=34?1:age<=49?2:age<=64?3:4;
 const words={thing:['耳机','电脑','家用电器','手机','厨房电器'][i],
 plan:['一次周末出游','一次公园野餐','一次短途旅行','一次近郊出游','一次户外活动'][i],
 items:['抽屉里的小物品','柜子里的杂物','常用的生活用品','书架上的书','储物盒里的东西'][i]};
 return text.replace(/\{(thing|plan|items)\}/g,(_,key:keyof typeof words)=>words[key])
  .replaceAll('手机里的照片',['手机里的日常照片','电脑里的旅行照片','手机里保存的图片','相机导出的照片','手机里的旧照片'][i])
  .replaceAll('一道菜',['一盘炒饭','一份炖菜','一碗面','一盘炒菜','一道蒸菜'][i])
  .replace(/尝试[一一种个]+新兴趣/g,['学着拍照片','学着做点心','学着剪一段视频','学着画画','学着种花'][i]);
}
