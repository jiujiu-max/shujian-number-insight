export function modifierAgeScene(star: PortraitStar, mood: ModifierMood, domain: ReadingDomain, age: number): string | undefined {
  const precise=preciseModifierScene(star,mood,domain,age);
  if(precise) return precise;
  const stage = age <= 24 ? 0 : age <= 34 ? 1 : age <= 49 ? 2 : age <= 64 ? 3 : 4;
  let key: string | undefined;
  if (mood === "hidden" || mood === "mixed") {
    if (domain === "work") key = ({shengqi:"help",tianyi:"speakWork",yannian:"speakWork",fuwei:"hesitate",jueming:"carryQuietly",wugui:"changeQuietly",liusha:"quietDisagree",huohai:"speakWork"})[star];
    if (domain === "money") key = ({shengqi:"moneyTerms",tianyi:"tiedMoney",yannian:"askPay",fuwei:"reluctantMoney",jueming:"tiedMoney",wugui:undefined,liusha:"softMoney",huohai:"moneyTerms"})[star];
    if (domain === "relationship") key = star === "shengqi" ? "promiseSocial" : "quietDisagree";
  } else if (mood === "empty") {
    if (domain === "work") key = ({fuwei:'hesitate',wugui:'switch',shengqi:'help',liusha:'requests',tianyi:'extraWork',huohai:'undecidedWork',jueming:'unfinished',yannian:'unfinished'})[star];
    if (domain === "money") key = star === "wugui" ? undefined : star === "shengqi" ? "moneyTerms" : "leftLittle";
    if (domain === "relationship") key = star === "jueming" || star === "huohai" ? "quietDisagree" : "fadedContact";
  }
  return key ? SCENES[key][stage] : undefined;
}
