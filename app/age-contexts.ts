export function exactAgeContext(pattern: string | undefined, age: number): string | undefined {
  if (!pattern) return undefined;
  const group = groups.find(item => item.patterns.includes(pattern));
  const index = age <= 24 ? 0 : age <= 34 ? 1 : age <= 49 ? 2 : age <= 64 ? 3 : 4;
  return group?.settings[index];
}
