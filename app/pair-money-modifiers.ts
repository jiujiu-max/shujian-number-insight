import type { NumberGroup } from './number-composition';
import { modifierMood } from './report-focus';

// These subjects already differ in the pair rules. Keep that distinction when
// 0/5 changes how it is expressed, without assigning a new outcome or score.
export function pairMoneyModifier(group:NumberGroup,age:number) {
 const pair=group.base.slice(0,2);
 if(!['16','18','37','63'].includes(pair)||(!group.zeroCount&&!group.fiveCount))return;
 const i=age<=24?0:age<=34?1:age<=49?2:age<=64?3:4;
 const thing=['耳机','电脑','家用电器','手机','厨房电器'][i];
 const person=['一起出游的朋友','常联系的朋友','一起办事的人','老朋友','一起参加活动的人'][i];
 const mood=modifierMood(group);
 const empty=group.modifierRuns.some(r=>r.position==='trailing'&&r.digits.includes('0'));
 const hidden:Record<string,[string,string,string]>={
  '16':['钱还没拿到就想买，手头紧又不愿说。','你心里想着过几天就有钱，先把想买的选好。一起花钱时，又不好意思说自己还在等钱，别人便以为你随时能付。到了付款那天，才发现预想的钱还没来。',`你想买${thing}，心里指望一笔还没收到的钱。${person}问要不要一起下单，你说可以，没提自己还在等钱。真要付款时，就得先拿生活费补。`],
  '18':['这笔先付、那笔先垫，自己也没算清一共花了多少。','你记得每笔钱是做什么用的，却没有把它们放在一起算。卡里还有余额，就觉得还能花。等几笔退款、借出去的钱都没回来，才发现生活费也被一起花掉了。',`你订了一件${thing}，又替${person}垫了一笔，还在等另一笔退款。每次都觉得卡里还有钱，没合起来算。几天后想买日用品，才发现剩下的钱比以为的少得多。`],
  '37':['借钱、垫钱时答应了，什么时候还却没问。','你怕刚答应帮忙就问还钱时间，显得不信任对方，便把这个问题咽了回去。对方说过几天，你也没有追问。自己要用钱时，只能重新开口，再等对方安排。',`${person}请你先垫买${thing}的钱，你想问哪天还，又觉得刚答应就问不太好。对方说回头转，你便没再说。后来自己要交一笔费用，才发现根本没约过还钱的日子。`],
  '63':['等着钱用，却把催款的话一次次删掉。','你知道有一笔钱还没收到，心里也着急，但发消息时又怕让人不舒服。对方以为你不急，便继续往后放；你越等越介意，又因为前面没提，更难突然开口。',`你准备买${thing}，正等着${person}还之前垫的钱。打开聊天框，打了“今天能转吗”，又怕显得催得紧，最后只问了句最近忙不忙。钱的事仍没说。`]
 };
 const visible:Record<string,[string,string,string]>={
  '16':['钱还没收到，想买的已经下单了。','你看中就想早点买，不愿因为钱晚几天到而再等。于是先分期、先用生活费付，觉得那笔钱来了就补上。可什么时候收到并不由你定，还款的日子却已经定了。',`看中${thing}后，你想着过几天有钱进来，就先下单分期。跟${person}聊起来时还说这样不用等。到了还款那天，钱没收到，只好先从生活费里拿。`],
  '18':['几件事都愿意先出钱，最后把生活费也花进去了。','买东西愿意先付款，别人有需要也愿意先垫。每笔单独看似乎都花得起，可钱都是从同一张卡出去的。自己的吃饭、出门还要花多少，没有一起算，就容易越花越紧。',`你给${thing}付了款，${person}又请你帮忙买一件东西，你也先付了。看到卡里还有钱，接着又买了日用品。晚些时候要交固定费用，才发现前面几笔把钱花得差不多了。`],
  '37':['借钱、垫钱很爽快，还钱的日子却容易漏说。','你想先帮人把事办了，钱什么时候还可以后面再谈。对方说回头给，你就先付。帮忙已经完成，还钱却没有约好日期，自己要用时就容易被动。',`${person}说买${thing}还差一点，你马上替他付了，说回头转就行。过了几天，对方还没动静。你要交一笔费用才去问，他却说以为不着急。`],
  '63':['会开口问钱，但一句“不急”又让人以为还能等。','你并非完全不问，可能已经提过一次，却又习惯补一句方便时再给。对方听到的是可以晚一点，你心里想的却是最好尽快。两个人没说定哪天，钱的事就还悬着。',`你提醒${person}转回之前垫的钱，随后又加了一句“不急，方便就行”。其实你正想拿来买${thing}。过了几天还没收到，你才发现自己想尽快拿到，对方却以为还能等等。`]
 };
 const emptyRows:Record<string,[string,string,string]>={
  '16':['下个月的钱提前花了，要还的时候却还没收到。','你先买了东西，想着下一笔钱一到就能补上。可钱晚到了，分期和账单不会跟着等。最后只能先拿吃饭、出门的钱还，买东西时的轻松变成了之后几天的紧巴。',`你分期买了${thing}，原本等着一笔钱来还。到了还款那天还没收到，${person}又约你出门，你只能推掉：生活费得先拿去还这笔账。`],
  '18':['付出去的几笔钱没回来，自己要用的也不够了。','有的在等退款，有的是替人先垫的，你觉得迟早会回来，就没有单独留够生活费。可这几笔都没按想的时间回来，自己要花的钱却不会少，只能先省着用。',`买${thing}退货后还没收到退款，${person}让你垫的钱也没还。你原本觉得过几天就有了，又照常花。等到需要买日用品，才发现钱都在等，卡里却不够用了。`],
  '37':['钱先借了、垫了，自己要用时却还没拿回来。','当时只顾把事情办好，没有说定什么时候还。后来自己急着用，对方又说再等几天。账上记着他欠你多少，眼前却没有这笔钱可用，自己的付款还得另想办法。',`你替${person}垫了买${thing}的钱，当时没问还钱日期。后来自己要交费用，再问时对方说还要几天。你只好先拿原本准备存下的钱付。`],
  '63':['不好意思要，等到自己急用时还是没收到。','你一次次想着对方应该会主动还，就没有明确问哪天转。对方也没有把这件事放在前面。等到自己必须用钱，再怕开口也躲不过，前面的等待反而耽误了自己的安排。',`你想买${thing}，一直等${person}把垫的钱转来。几次聊天都想提，又觉得他应该记得。等到真要付款，钱还是没来，你只能把要买的先放回购物车。`]
 };
 const row=empty?emptyRows[pair]:(mood==='hidden'?hidden:visible)[pair];
 let [lead,explanation,example]=row;
 if(mood==='mixed'&&!empty){
  [lead,explanation,example]=hidden[pair];
  explanation=visible[pair][1].split('。')[0]+'。'+explanation;
 }
 return {lead,explanation,example};
}
