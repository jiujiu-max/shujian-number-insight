// Keep hash links inside the local report: a router navigation can remount the
// form and discard the browser-only result. Modified clicks retain native use.
function scrollWithinPage(event: MouseEvent<HTMLElement>) {
  if(event.defaultPrevented || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey || event.button !== 0) return;
  const link = (event.target as Element).closest('a[href^="#"]');
  const id = link?.getAttribute('href')?.slice(1);
  const target = id ? document.getElementById(id) : null;
  if(!target) return;
  event.preventDefault();
  target.scrollIntoView({behavior:'smooth',block:'start'});
}

