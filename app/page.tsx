function findSequenceHits(source: string): SequenceHit[] {
  const hits: SequenceHit[] = [];

  SEQUENCE_RULES.forEach((rule) => {
    let fromIndex = 0;
    while (fromIndex <= source.length - rule.pattern.length) {
      const index = source.indexOf(rule.pattern, fromIndex);
      if (index === -1) break;
      hits.push({
        rule,
        index,
        endIndex: index + rule.pattern.length - 1,
      });
      fromIndex = index + 1;
    }
  });

  return hits.sort(
    (a, b) =>
      a.index - b.index ||
      b.rule.pattern.length - a.rule.pattern.length ||
      a.endIndex - b.endIndex,
  );
}

function chooseSequenceHits(hits: SequenceHit[], limit = 3) {
  if (hits.length <= limit) return hits;

  const first = hits[0];
  const tail = hits
    .slice()
    .sort(
      (a, b) =>
        b.rule.pattern.length - a.rule.pattern.length ||
        b.endIndex - a.endIndex,
    )[0];
  const middleTarget = (first.index + tail.endIndex) / 2;
  const middle = hits
    .filter((hit) => hit !== first && hit !== tail)
    .sort(
      (a, b) =>
        Math.abs((a.index + a.endIndex) / 2 - middleTarget) -
          Math.abs((b.index + b.endIndex) / 2 - middleTarget) ||
        b.rule.pattern.length - a.rule.pattern.length,
    )[0];

  return [first, middle, tail]
    .filter((hit): hit is SequenceHit => Boolean(hit))
    .filter((hit, index, items) => items.indexOf(hit) === index)
    .sort((a, b) => a.index - b.index)
    .slice(0, limit);
}

function applySequenceDomain(
  base: DomainInsight,
  hits: SequenceHit[],
  domain: "relationship" | "work" | "money",
  matches: Match[],
  sourceOffset: number,
): DomainInsight {
  const hit = hits
    .filter((item) => Boolean(item.rule[domain]))
    .sort(
      (a, b) =>
        b.rule.pattern.length - a.rule.pattern.length ||
        b.endIndex - a.endIndex,
    )[0];

  if (!hit) return base;

  const supportingMatches = matches.filter((match) =>
    match.index >= hit.index + sourceOffset && match.endIndex <= hit.endIndex + sourceOffset,
  );

  return {
    ...base,
    numbers: `${hit.rule.pattern} 连续组合`,
    text: /[。？！]$/.test(hit.rule[domain]!)
      ? hit.rule[domain]!
      : hit.rule[domain]!.replace(/[；]+$/, "") + "。",
    matches: supportingMatches,
    keys: Array.from(new Set(supportingMatches.map((match) => match.key))),
    sequencePattern: hit.rule.pattern,
    lead: hit.rule.leads?.[domain],
    question: hit.rule.questions?.[domain],
  };
}

