function findRepeatedDigitInsight(body: string) {
  const counts = [...body].reduce((result, digit) => {
    result.set(digit, (result.get(digit) ?? 0) + 1);
    return result;
  }, new Map<string, number>());
  const repeated = [...counts.entries()]
    .filter(([digit, count]) => count >= 3 && DIGIT_REPEAT_VOICES[digit])
    .sort(
      (a, b) =>
        b[1] - a[1] ||
        body.lastIndexOf(b[0]) - body.lastIndexOf(a[0]),
    )[0];

  if (!repeated) return undefined;
  const [digit, count] = repeated;
  return { digit, count, voice: DIGIT_REPEAT_VOICES[digit] };
}

