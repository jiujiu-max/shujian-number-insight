// phone use causes an outcome. Keep the existing position-specific exceptions.
export function radarTakeaway(star: PortraitStar, mood: ModifierMood, group?: NumberGroup, lead = "") {
  const clean = (copy: string) => copy.replace(/[。！？]+/g, "，").replace(/，+$/g, "");
  const person = TYPE_IDENTITIES[star].role;
  const pairConcern=pairFocusConcern(star,group);
  if(pairConcern) return `你${person}；${pairConcern}`;
  const chain = conditionalProgression(star, mood, group);
  if (!chain) return `你${person}；${clean(lead || TYPE_IDENTITIES[star].motto)}。`;
  const specific = group && (['856','154','145','959'].includes(group.raw)
    || group.base === '99' && mood === 'plain' || group.base === '82' && mood === 'plain');
  if (!specific && lead) return `你${person}；${clean(lead)}。`;
  const tendency = specific ? `${chain[0]}，${chain[1]}` : clean(focusTrap(star, mood));
  const amplified: Record<PortraitStar,string> = {
    shengqi:"别人的事忙完了，自己的事却一直拖着",
    tianyi:"你付出得越来越多，却不一定得到同样的回应",
    yannian:"大家都等着你处理，你想休息也放不下",
    fuwei:"碰到新情况，原来的办法就不一定管用了",
    jueming:"自己的时间越挤越少，还容易把事情耽误了",
    wugui:"看着一直在忙，真正做完的事却不多",
    liusha:"自己的安排和心情，都容易被别人的反应打乱",
    huohai:"想说的道理没讲清，反而先把人得罪了",
  };
  const outcome = !specific && (mood === 'visible' || mood === 'growing') ? amplified[star] : chain[2];
  return `你${person}，${tendency}；如果一直这样，${outcome}。`;
}

