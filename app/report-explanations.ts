export function domainConsequence(star: PortraitStar, mood: ModifierMood, domain: ReadingDomain, group?: NumberGroup) {
  if(mood === "mixed") return "";
  // Don't force a negative generic consequence onto the course's specific
  // help/sustained-client/quiet-99 readings.
  if(group && (['856','154','145','959'].includes(group.raw) || group.base === '99' || group.base === '82' && mood === 'plain')) return "";
  return CONSEQUENCES[star][domain === 'work' ? 0 : domain === 'money' ? 1 : 2];
}

export function readingExplanation(star: PortraitStar, mood: ModifierMood, domain: ReadingDomain) {
  // Mixed 0/5 has two distinct effects in the source copy. Avoid adding a
  // single generic reason which could contradict one of them.
  if (mood === "mixed") return "";
  return REASONS[star][mode(mood)][domain === "work" ? 0 : domain === "money" ? 1 : 2];
}

